const fs = require('fs');
const path = require('path');

const distDir = path.join(__dirname, '..', 'dist');
const entryPath = path.join(distDir, 'server.js');
const assetsSource = path.join(__dirname, '..', 'assets');
const assetsTarget = path.join(distDir, 'assets');

function copyDirRecursive(source, target) {
  if (!fs.existsSync(source)) return;
  fs.mkdirSync(target, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const from = path.join(source, entry.name);
    const to = path.join(target, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(from, to);
    } else {
      fs.copyFileSync(from, to);
    }
  }
}

fs.mkdirSync(distDir, { recursive: true });
copyDirRecursive(assetsSource, assetsTarget);
fs.writeFileSync(
  entryPath,
  [
    '// Generated by npm run build — Hostinger entry when output dir is "dist".',
    "const path = require('path');",
    "require('dotenv').config({ path: path.join(__dirname, '..', '.env') });",
    "process.env.NODE_ENV = process.env.NODE_ENV || 'production';",
    "console.log(`[Flex HRM] Booting API — NODE_ENV=${process.env.NODE_ENV} PORT=${process.env.PORT || '(unset — use npm start in hPanel)'}`);",
    "require('./main');",
    '',
  ].join('\n'),
);

console.log('Wrote dist/server.js for Hostinger Node.js hosting');
